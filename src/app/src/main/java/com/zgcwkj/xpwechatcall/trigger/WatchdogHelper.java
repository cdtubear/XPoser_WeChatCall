package com.zgcwkj.xpwechatcall.trigger;

import android.content.Context;

import com.zgcwkj.comm.LogHelp;

import java.io.File;
import java.io.FileOutputStream;
import java.nio.charset.StandardCharsets;

/**
 * root 看门狗
 *
 * 在 /data/adb/service.d 写入一个开机自启的 root 脚本，每 30 秒检查
 * HTTP 端口是否还在监听；不在就执行 am start-foreground-service 把服务拉起来。
 *
 * 看门狗运行在 App 进程之外，因此 App 被划掉、被系统回收甚至被强行停止时，
 * 只要 root 管理器的 service.d 还在，就能把服务重新拉起来。
 *
 * 支持 Magisk / KernelSU / APatch 等使用 /data/adb/service.d 的 root 方案。
 */
public final class WatchdogHelper {

    private static final String TAG = "XpWeChatCall";

    /** root 管理器通用的开机脚本目录 */
    public static final String SERVICE_DIR = "/data/adb/service.d";
    public static final String SCRIPT_PATH = SERVICE_DIR + "/xp_wechatcall_watchdog.sh";
    private static final String PID_PATH = "/data/local/tmp/xp_wechatcall_watchdog.pid";
    private static final String LOG_PATH = "/data/local/tmp/xp_wechatcall_watchdog.log";
    private static final String SCRIPT_MARKER = "XpWeChatCall root watchdog v2";

    private WatchdogHelper() {
    }

    /**
     * 当前 root 环境是否支持 service.d 开机脚本
     */
    public static boolean isSupported(Context context) {
        if (!RootShell.hasRoot(context)) {
            return false;
        }
        var result = RootShell.runAsRoot(
            "if [ -d /data/adb ]; then echo xp_supported; fi");
        return result.ok && result.output.contains("xp_supported");
    }

    /**
     * 看门狗脚本是否已安装
     */
    public static boolean isInstalled(Context context) {
        if (!RootShell.hasRoot(context)) {
            return false;
        }
        var result = RootShell.runAsRoot(
            "if [ -f '" + SCRIPT_PATH + "' ] && grep -q '" + SCRIPT_MARKER
                + "' '" + SCRIPT_PATH + "' 2>/dev/null; then echo xp_installed; fi");
        return result.ok && result.output.contains("xp_installed");
    }

    /**
     * 看门狗进程是否正在运行
     */
    public static boolean isRunning(Context context) {
        if (!RootShell.hasRoot(context)) {
            return false;
        }
        return runRoot(killOldCommand(false)).contains("xp_running");
    }

    /**
     * 安装并立即启动看门狗
     */
    public static boolean install(Context context) {
        if (!isSupported(context)) {
            LogHelp.w(TAG, "watchdog install skipped: service.d not supported");
            return false;
        }
        File temp = null;
        try {
            temp = new File(context.getCacheDir(), "xp_wechatcall_watchdog.sh");
            try (var out = new FileOutputStream(temp)) {
                out.write(buildScript(context.getPackageName())
                    .getBytes(StandardCharsets.UTF_8));
            }
            var command = "mkdir -p '" + SERVICE_DIR + "'; "
                + killOldCommand(true)
                + "cp '" + temp.getAbsolutePath() + "' '" + SCRIPT_PATH + "'; "
                + "chmod 755 '" + SCRIPT_PATH + "'; "
                + "nohup sh '" + SCRIPT_PATH + "' >/dev/null 2>&1 </dev/null &";
            RootShell.runAsRoot(command);
            var installed = isInstalled(context);
            LogHelp.i(TAG, "watchdog install " + (installed ? "ok" : "failed"));
            return installed;
        } catch (Throwable e) {
            LogHelp.e(TAG, "watchdog install failed: " + e.getMessage(), e);
            return false;
        } finally {
            if (temp != null) {
                //noinspection ResultOfMethodCallIgnored
                temp.delete();
            }
        }
    }

    /**
     * 停止并删除看门狗
     */
    public static boolean uninstall(Context context) {
        if (!RootShell.hasRoot(context)) {
            return false;
        }
        var command = killOldCommand(true)
            + "rm -f '" + SCRIPT_PATH + "'; echo xp_removed";
        var result = RootShell.runAsRoot(command);
        var removed = result.ok && !isInstalled(context);
        LogHelp.i(TAG, "watchdog uninstall " + (removed ? "ok" : "failed"));
        return removed;
    }

    /**
     * 生成会随 App 更新的看门狗脚本
     */
    private static String buildScript(String pkg) {
        return "#!/system/bin/sh\n"
            + "# " + SCRIPT_MARKER + "\n"
            + "# Generated by the app. Remove it from the app settings before uninstalling.\n"
            + "PKG='" + pkg + "'\n"
            + "SVC=\"$PKG/.trigger.TriggerService\"\n"
            + "RECEIVER=\"$PKG/.trigger.BootReceiver\"\n"
            + "ACTION=\"$PKG.action.TRIGGER_START\"\n"
            + "WAKE_ACTION=\"$PKG.action.WATCHDOG_START\"\n"
            + "PREFS=\"/data/data/$PKG/shared_prefs/trigger_config.xml\"\n"
            + "PID_FILE='" + PID_PATH + "'\n"
            + "LOG='" + LOG_PATH + "'\n"
            + "echo $$ > \"$PID_FILE\"\n"
            + "while true; do\n"
            + "  if [ ! -d \"/data/data/$PKG\" ]; then\n"
            + "    sleep 60\n"
            + "    [ -d \"/data/data/$PKG\" ] || exit 0\n"
            + "    continue\n"
            + "  fi\n"
            + "  if grep -q 'name=\"enabled\" value=\"true\"' \"$PREFS\" 2>/dev/null; then\n"
            + "    PORT=$(sed -n 's/.*name=\"port\" value=\"\\([0-9][0-9]*\\)\".*/\\1/p' \"$PREFS\" 2>/dev/null | head -n 1)\n"
            + "    [ -n \"$PORT\" ] || PORT=8790\n"
            + "    HEX=$(printf '%04X' \"$PORT\" 2>/dev/null)\n"
            + "    if [ -z \"$HEX\" ] || ! grep -qi \":$HEX \" /proc/net/tcp /proc/net/tcp6 2>/dev/null; then\n"
            + "      # 先广播唤醒 App（BootReceiver 是 exported，且不会暴露 TriggerService），\n"
            + "      # 再用 root 直接拉起作为兜底。两种方式重复触发也不会重复监听端口。\n"
            + "      am broadcast -n \"$RECEIVER\" -a \"$WAKE_ACTION\" -f 0x00000020 >/dev/null 2>&1\n"
            + "      am start-foreground-service -n \"$SVC\" -a \"$ACTION\" >/dev/null 2>&1\n"
            + "      echo \"$(date '+%Y-%m-%d %H:%M:%S') restart service\" >> \"$LOG\"\n"
            + "    fi\n"
            + "  fi\n"
            + "  sleep 30\n"
            + "done\n";
    }

    /**
     * 杀掉旧的看门狗进程；kill=false 时只检查是否在运行
     */
    private static String killOldCommand(boolean kill) {
        var command = "PID=$(cat '" + PID_PATH + "' 2>/dev/null); "
            + "if [ -n \"$PID\" ] && [ -d \"/proc/$PID\" ]; then "
            + "CMD=$(cat \"/proc/$PID/cmdline\" 2>/dev/null); "
            + "case \"$CMD\" in *xp_wechatcall_watchdog*) ";
        if (kill) {
            command += "kill \"$PID\" 2>/dev/null; ";
        } else {
            command += "echo xp_running; ";
        }
        command += ";; esac; fi; ";
        if (kill) {
            command += "rm -f '" + PID_PATH + "'; ";
        }
        return command;
    }

    private static String runRoot(String command) {
        var result = RootShell.runAsRoot(command);
        return result.ok ? result.output : "";
    }
}
